"""Generate the A+ Atelier Soft material images as tiny PNG data URIs.

aura  : page background glow (opaque RGB), stretched to the screen.
board : outfit board gradient (opaque RGB).
glow  : blush highlight for the Stylist's Note panel (RGBA).

Prints a Jac module to stdout and refuses to write an aura that would drop
secondary text (#806048) under 4.5:1 anywhere.

Regenerate:  python3 scripts/make_materials.py > ui/materials.jac
"""
import base64, math, struct, sys, zlib


def png(width, height, rows, alpha):
    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    raw = b"".join(b"\x00" + bytes(row) for row in rows)
    ctype = 6 if alpha else 2
    ihdr = struct.pack(">IIBBBBB", width, height, 8, ctype, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def hex_rgb(h):
    return [int(h[i:i + 2], 16) for i in (1, 3, 5)]


def lum(rgb):
    out = []
    for v in rgb:
        c = v / 255
        out.append(c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4)
    return 0.2126 * out[0] + 0.7152 * out[1] + 0.0722 * out[2]


def contrast(a, b):
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


BASE = hex_rgb("#F7F3EF")
BLUSH = hex_rgb("#F1D6CB")
SAND = hex_rgb("#EBDCC6")
SECONDARY = hex_rgb("#806048")


def aura(w=90, h=196, strength=0.5):
    # (cx, cy, radius as a share of width, colour) in 0..1 screen space.
    blobs = [
        (1.02, 0.02, 0.62, BLUSH),
        (-0.08, 0.40, 0.58, SAND),
        (1.08, 0.74, 0.60, BLUSH),
        (0.10, 1.04, 0.62, SAND),
    ]
    rows, worst = [], 99.0
    for y in range(h):
        row = []
        for x in range(w):
            px, py = x / (w - 1), y / (h - 1) * (h / w)
            colour = list(BASE)
            for cx, cy, r, c in blobs:
                d = math.hypot(px - cx, py - cy * (h / w)) / r
                t = strength * math.exp(-d * d * 2.2)
                colour = [colour[i] + (c[i] - colour[i]) * t for i in range(3)]
            rgb = [max(0, min(255, round(v))) for v in colour]
            worst = min(worst, contrast(SECONDARY, rgb))
            row += rgb
        rows.append(row)
    return png(w, h, rows, False), worst


def board(w=56, h=64):
    top, bottom = hex_rgb("#FBF6F1"), hex_rgb("#ECE1D4")
    rows = []
    for y in range(h):
        row = []
        for x in range(w):
            t = min(1.0, (x / (w - 1)) * 0.35 + (y / (h - 1)) * 0.75)
            c = [top[i] + (bottom[i] - top[i]) * t for i in range(3)]
            d = math.hypot((x / (w - 1) - 0.45) * 1.2, (y / (h - 1) - 0.32))
            g = 0.55 * math.exp(-d * d * 9)
            c = [c[i] + (255 - c[i]) * g for i in range(3)]
            row += [max(0, min(255, round(v))) for v in c]
        rows.append(row)
    return png(w, h, rows, False)


def glow(size=64):
    c = hex_rgb("#F3D9CE")
    rows = []
    for y in range(size):
        row = []
        for x in range(size):
            d = math.hypot(x / (size - 1) - 0.5, y / (size - 1) - 0.5) / 0.5
            a = max(0.0, 0.75 * math.exp(-d * d * 2.6) - 0.02)
            row += c + [round(a * 255)]
        rows.append(row)
    return png(size, size, rows, True)


def uri(data):
    return "data:image/png;base64," + base64.b64encode(data).decode("ascii")


aura_png, worst = aura()
if worst < 4.5:
    sys.exit(f"secondary text would drop to {worst:.2f}:1 over the aura")
board_png, glow_png = board(), glow()
sys.stderr.write(f"aura {len(aura_png)}B (worst secondary contrast {worst:.2f}:1), board {len(board_png)}B, glow {len(glow_png)}B\n")
